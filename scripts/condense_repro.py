#!/usr/bin/env python
"""
Condense the reproduction run outputs into a small, git-friendly `repro/` folder.

Inputs (all generated by scripts/repro_launcher.py and scripts/plot_repro.py):
    ~/bpo_repro                       full 340-run reproduction
    ~/bpo_repro_calib                 first speed-calibration pass (+ ~/bpo_repro_calib.launcher.log)
    ~/bpo_repro_calib2                second calibration pass (cpu / gpu / isaac queues)
    <repo>/logs/rsl_rl, <repo>/outputs IsaacLab run dirs and their Hydra dirs

What is kept:
    results/   exported tables, figures, and the reward / ratio curves downsampled to
               <= N points per series (curves.npz; plot_repro.py reads it when curves.pkl is absent)
    campaigns/<campaign>/
               launcher log(s) and job-state JSON as written by the launcher
               job_logs/<job>.log  config header + last metrics block + any tracebacks of each job log
               configs/<job>/      Hydra config.yaml + overrides.yaml of each SB3 job
    campaigns/isaaclab/
               index.csv           run dir -> agent cfg, env cfg, git diff (deduplicated by content)
               agent/, env/, git/  the unique files

What is dropped (all of it is on wandb, see repro/README.md): TensorBoard event files, wandb run dirs,
videos, checkpoints, and the bulk of the per-step console output.

    python scripts/condense_repro.py [--dest repro] [--points 500]
"""
import argparse
import csv
import glob
import hashlib
import json
import os
import pickle
import re
import shutil

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME = "/home2/hua48722"
CAMPAIGNS = {
    "repro": (f"{HOME}/bpo_repro", ["launcher.log", "jobs-BPO-repro.json"]),
    "calib": (f"{HOME}/bpo_repro_calib", ["jobs-BPO-calib.json", f"{HOME}/bpo_repro_calib.launcher.log"]),
    "calib2": (f"{HOME}/bpo_repro_calib2", ["cpu.launcher.log", "gpu.launcher.log", "isaac.launcher.log",
                                             "jobs-BPO-calib2-cpu.json", "jobs-BPO-calib2-gpu.json",
                                             "jobs-BPO-calib2-isaac.json"]),
}
DASH = re.compile(r"^-{20,}\s*$")
ISAAC_ITER = re.compile(r"Learning iteration \d+/\d+")
HEADER_END = re.compile(r"^-{20,}\s*$|^#{20,}\s*$|Learning iteration")


def condense_log(src, dst, head_cap=300, tb_lines=40):
    with open(src, errors="replace") as f:
        lines = f.read().splitlines()
    n = len(lines)
    # 1. header: resolved config and startup messages, up to the first metrics block
    h = next((i for i, l in enumerate(lines) if HEADER_END.search(l)), n)
    keep = [(0, min(h, head_cap))]
    # 2. last metrics block: SB3 table (between the last two dashed lines) or the last IsaacLab iteration
    dashes = [i for i, l in enumerate(lines) if DASH.match(l)]
    iters = [i for i, l in enumerate(lines) if ISAAC_ITER.search(l)]
    if iters:
        keep.append((max(iters[-1] - 2, 0), min(iters[-1] + 40, n)))
    elif len(dashes) >= 2:
        keep.append((dashes[-2], min(dashes[-1] + 1, n)))
    # 3. every traceback, and the last lines (exit message)
    for i, l in enumerate(lines):
        if l.startswith("Traceback"):
            keep.append((i, min(i + tb_lines, n)))
    keep.append((max(n - 15, 0), n))
    keep.sort()
    merged = []
    for a, b in keep:
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    out, prev = [], 0
    for a, b in merged:
        if a > prev:
            out.append(f"... [{a - prev} lines elided] ...")
        out += lines[a:b]
        prev = b
    if prev < n:
        out.append(f"... [{n - prev} lines elided] ...")
    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")


def downsample(x, y, n):
    if len(x) <= n:
        return x, y
    idx = np.unique(np.linspace(0, len(x) - 1, n).round().astype(int))
    return x[idx], y[idx]


def condense_curves(pkl, dst, n):
    with open(pkl, "rb") as f:
        data = pickle.load(f)
    arrays, index = {}, []
    for k, ((env, algo, seed), tags) in enumerate(data.items()):
        for t, (x, y) in tags.items():
            x, y = downsample(np.asarray(x), np.asarray(y), n)
            name = f"r{k}_{len(index)}"
            arrays[name + "_x"] = x.astype(np.float64)
            arrays[name + "_y"] = y.astype(np.float32)
            index.append([name, env, algo, seed, t])
    arrays["index"] = np.array(json.dumps(index))
    np.savez_compressed(dst, **arrays)


def sha(path):
    return hashlib.md5(open(path, "rb").read()).hexdigest()[:10]


def condense_isaac(dest):
    root = os.path.join(dest, "campaigns", "isaaclab")
    for sub in ("agent", "env", "git"):
        os.makedirs(os.path.join(root, sub), exist_ok=True)
    rows = []
    for run in sorted(glob.glob(os.path.join(REPO, "logs", "rsl_rl", "*", "*"))):
        row = {"task": os.path.basename(os.path.dirname(run)), "run_dir": os.path.basename(run)}
        for col, rel, sub in (("agent_cfg", "params/agent.yaml", "agent"), ("env_cfg", "params/env.yaml", "env"),
                              ("git_diff", "git/bounded_ratio_rl.diff", "git")):
            p = os.path.join(run, rel)
            if os.path.exists(p):
                ext = os.path.splitext(p)[1]
                name = f"{sub}/{sha(p)}{ext}"
                shutil.copy(p, os.path.join(root, name))
                row[col] = name
            else:
                row[col] = ""
        rows.append(row)
    with open(os.path.join(root, "index.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["task", "run_dir", "agent_cfg", "env_cfg", "git_diff"])
        w.writeheader()
        w.writerows(rows)
    # Hydra overrides of each IsaacLab launch (config.yaml is the defaults plus these)
    hyd = os.path.join(root, "hydra_overrides")
    for p in sorted(glob.glob(os.path.join(REPO, "outputs", "*", "*", ".hydra", "overrides.yaml"))):
        date, time = p.split(os.sep)[-4:-2]
        os.makedirs(hyd, exist_ok=True)
        shutil.copy(p, os.path.join(hyd, f"{date}_{time}.yaml"))
    return len(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default=os.path.join(REPO, "repro"))
    ap.add_argument("--points", type=int, default=500, help="max points kept per curve")
    args = ap.parse_args()
    dest = args.dest

    res_src = os.path.join(CAMPAIGNS["repro"][0], "results")
    res = os.path.join(dest, "results")
    os.makedirs(os.path.join(res, "figures"), exist_ok=True)
    for f in ("per_run.csv", "summary.csv", "summary.md"):
        shutil.copy(os.path.join(res_src, f), res)
    for f in glob.glob(os.path.join(res_src, "figures", "*")):
        shutil.copy(f, os.path.join(res, "figures"))
    condense_curves(os.path.join(res_src, "curves.pkl"), os.path.join(res, "curves.npz"), args.points)

    for camp, (src, files) in CAMPAIGNS.items():
        d = os.path.join(dest, "campaigns", camp)
        os.makedirs(os.path.join(d, "job_logs"), exist_ok=True)
        for f in files:
            p = f if os.path.isabs(f) else os.path.join(src, f)
            name = "launcher.log" if p.endswith(".launcher.log") and camp == "calib" else os.path.basename(p)
            shutil.copy(p, os.path.join(d, name))
        logs = sorted(glob.glob(os.path.join(src, "logs", "*.log")))
        for p in logs:
            condense_log(p, os.path.join(d, "job_logs", os.path.basename(p)))
        for h in sorted(glob.glob(os.path.join(src, "sb3", "outputs", "*", ".hydra"))):
            job = os.path.basename(os.path.dirname(h))
            cd = os.path.join(d, "configs", job)
            os.makedirs(cd, exist_ok=True)
            for f in ("config.yaml", "overrides.yaml"):
                if os.path.exists(os.path.join(h, f)):
                    shutil.copy(os.path.join(h, f), cd)
        print(f"{camp}: {len(logs)} logs")
    print(f"isaaclab: {condense_isaac(dest)} run dirs")


if __name__ == "__main__":
    main()
